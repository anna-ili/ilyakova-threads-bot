// Жёсткий фильтр самых узнаваемых нейросетевых конструкций.
// Это не замена редактору по примерам, а последний предохранитель: лучше
// не показать черновик вообще, чем снова прислать Анне заведомый антистиль.

export function findHardStyleViolations(text: string): string[] {
  const checks: Array<[RegExp, string]> = [
    [/дело не в/i, 'конструкция «дело не в X»'],
    [/это не[^.!?]{0,100}[.!?]\s*(?:это|а)(?:\s|$)/i, 'конструкция «это не X — это Y»'],
    [
      /не потому,?\s+что[\s\S]{0,140}(?:\n\s*)?(?:а\s+потому|просто|потому,?\s+что)/i,
      'конструкция «не потому что — а/просто потому что»',
    ],
    [
      /(?:не убивает|не убивают|не нужен|не нужна|не нужно|не нужны)[^.!?]{0,140}[.!?]\s*(?:их\s+|ему\s+|ей\s+)?(?:убивает|убивают|нужен|нужна|нужно|нужны)/i,
      'декоративное противопоставление X/Y',
    ],
    [/(?:точка роста|главный инсайт|оставляет послевкусие)/i, 'нейросетевая стоп-фраза'],
    [/коридор без двер/i, 'выдуманная декоративная метафора'],
    [/систем[аыуе]\s+координат/i, 'нейросетевая метафора «система координат»'],
    [/не угадает[^.!?]{0,80}из воздуха/i, 'штамп «не угадает из воздуха»'],
    [/на вид прилично/i, 'нейросетевая связка «на вид прилично»'],
    [/нейросеть работает с тем, что ей дали/i, 'дежурная фраза о нейросети'],
    [/черновую работу[^.!?]{0,80}поруч/i, 'дежурная фраза про черновую работу'],
    [/постить можно[\s\S]{0,50}продавать/i, 'парная псевдомудрость «постить/продавать»'],
    [
      /без этого[^.!?]{0,140}(?:[.!?]|\n)\s*а по факту/i,
      'нейросетевая связка «без этого — а по факту»',
    ],
    [/выглядит как работа/i, 'псевдомудрая формула «выглядит как работа»'],
    [
      /что сейчас прода[её]м[^.!?]{0,100}кого вед[её]м[^.!?]{0,100}после чего/i,
      'симметричное перечисление этапов продажи',
    ],
    [/\b\p{L}+\s+есть,\s*\p{L}+\s+есть,\s*/iu, 'тройная симметричная формула'],
  ];

  return checks.filter(([pattern]) => pattern.test(text)).map(([, issue]) => issue);
}
