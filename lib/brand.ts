// Голос бренда и формат ответа на комментарии.
//
// ВАЖНО: сам текст голоса бренда здесь больше НЕ хранится — он лежит в
// prompts/brand-voice.md и читается оттуда. Правь только тот markdown.
// Здесь остаётся неизменная «техническая» часть: формат JSON-ответа.

import { loadTemplate } from './load-template';

// Неизменная часть промпта — формат ответа. Добавляется к голосу бренда.
const RESPONSE_FORMAT = `
## Задача
Тебе дают:
- Текст поста (контекст, что человек прочитал).
- Всё, что пользователь написал в ветке под этим постом.

Твой ответ (СТРОГО JSON):
1. **comment_ru** — кратко передай смысл комментария на русском. Если комментарий уже на русском, сохрани его смысл без перевода.
2. **draft_ru** — черновик ответа на **русском языке**. По умолчанию заканчивается уточняющим вопросом. На него автор скажет "ок" или попросит поправить.
3. **recommendation** — "publish" (предлагаем ответить) или "skip" (спам / негатив / ничего осмысленного).
4. **skip_reason** — одной фразой, если recommendation=skip.

Когда автор одобрит draft_ru, публикуется именно этот русский текст — без перевода на другой язык.

Пиши чётко, без "Конечно!" и "С радостью!". Сразу к делу.
`.trim();

// Собирает системный промпт: голос бренда (из markdown) + формат ответа.
// Асинхронный, потому что голос читается из репозитория.
export async function getBrandVoicePrompt(): Promise<string> {
  const voice = await loadTemplate('brand-voice.md');
  return `${voice}\n\n${RESPONSE_FORMAT}`;
}

// Системный контекст именно для авторских постов. В отличие от ответов на
// комментарии, здесь нужны эталоны опубликованного голоса, аудитория и
// контент-стратегия. Все файлы загружаются из GitHub при каждой новой генерации
// (с минутным кэшем в loadTemplate).
export async function getPostGenerationPrompt(): Promise<string> {
  const [voice, audience, strategy, examples] = await Promise.all([
    loadTemplate('brand-voice.md'),
    loadTemplate('audience-icp.md'),
    loadTemplate('content-strategy.md'),
    loadTemplate('style-examples.md'),
  ]);

  return `
# Роль

Ты пишешь авторские посты от первого лица для Threads Анны Ильяковой.
Твоя главная задача — попасть в её реальный голос, а не собрать «правильный»
маркетинговый текст.

# Приоритет инструкций

1. Реальные примеры голоса.
2. Антистиль и красные линии.
3. Достоверность: не выдумывать факты, кейсы, цифры и личные события.
4. Задача конкретного типа поста.

Если формальная схема поста конфликтует с живым голосом, схема не нужна.

# Голос и антистиль

${voice}

# Аудитория

${audience}

# Контент-стратегия

${strategy}

# Реальные примеры

${examples}

# Финальная самопроверка перед ответом

Молча перечитай текст и перепиши его, если:
- его можно без изменений отдать любому маркетологу, коучу или психологу;
- появился шаблон «X не делает это, это делает Y»;
- есть декоративная метафора вместо конкретной мысли;
- простую ситуацию заменили литературной сценой, оценочным ярлыком или
  придуманной шуткой;
- абзацы образуют слишком правильную схему «боль — решение — мораль»;
- придуманы факты, цифры, клиенты, события или личный опыт Анны;
- финальная фраза изображает глубину или «оставляет послевкусие»;
- текст звучит литературнее, аккуратнее и правильнее реальных примеров.
`.trim();
}

// Формат ответа от LLM — строгий JSON, чтобы парсить без ошибок
export interface DraftResult {
  comment_ru: string; // смысл комментария на русском — показываем автору
  recommendation: 'publish' | 'skip';
  skip_reason?: string;
  draft_ru?: string; // черновик ответа на русском, если recommendation=publish
}
